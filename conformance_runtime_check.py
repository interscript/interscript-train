"""Audit round 3 — does the SHIPPED python runtime pass its own
conformance fixture?

The fixture vectors were generated by the reference decoder (trivially
true); this job runs the actual client path — interscript_ml.Model
(sha256-verifying loader + runtime decode) — against the fp16 zip and
byte-compares. A mismatch here means the client contract is broken and
nothing ships.

Usage (cpu-basic):
    python /ckpt/run-066-urd-diac-base/conformance_runtime_check.py
"""

import json
import os
import sys
from pathlib import Path

sys.path.insert(0, "/ckpt/run-066-urd-diac-base/runtime-check/src")

from interscript_ml import Model  # noqa: E402

RUN = Path("/ckpt/run-066-urd-diac-base")
ZIP = RUN / "export" / "urd-diac-base-1.0-fp16.zip"
VECTORS = RUN / "urd-diac-base-vectors.json"
OUT = RUN / "runtime-conformance-verdict.json"

vectors = json.loads(VECTORS.read_text(encoding="utf-8"))
model = Model(str(ZIP))

mismatches = []
for i, v in enumerate(vectors["vectors"]):
    got = model.translate(v["src"])
    if got != v["out"]:
        mismatches.append({"index": i, "src": v["src"],
                           "expected": v["out"], "got": got})

res = {
    "runtime": "interscript_ml.Model",
    "model": vectors["model"],
    "checked": len(vectors["vectors"]),
    "passed": not mismatches,
    "mismatches": mismatches[:5],
}
print(json.dumps(res, ensure_ascii=False), flush=True)
OUT.write_text(json.dumps(res, ensure_ascii=False, indent=1), encoding="utf-8")
